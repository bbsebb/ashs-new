package fr.hoenheimsports.backend.teamservice.entities;

/**
 * Enum representing the role of a staff member within a team.
 */
public enum Role {

    /**
     * Head coach of the team.
     */
    COACH,

    /**
     * Assistant coach of the team.
     */
    ASSISTANT,

    /**
     * Support staff member (e.g., team manager, physical therapist).
     */
    SUPPORT,

}
